ALTER TABLE STM_LITERAL_TRANSLATION
  ADD COLUMN LTR_LANID INT4;

UPDATE STM_LITERAL_TRANSLATION
SET LTR_LANID = COALESCE(
  (
    SELECT lan.LAN_ID
    FROM STM_LANGUAGE lan
    WHERE lan.LAN_SHORTNAME = (
      SELECT conf.CNF_VALUE
      FROM STM_CONF conf
      WHERE conf.CNF_NAME = 'language.default'
    )
  ),
  (
    SELECT MIN(lan.LAN_ID)
    FROM STM_LANGUAGE lan
  )
)
WHERE LTR_LANID IS NULL;

UPDATE STM_LITERAL_TRANSLATION_VALUE ltv
SET LTV_VALUE = lt.LTR_LITERAL
FROM STM_LITERAL_TRANSLATION lt
WHERE lt.LTR_ID = ltv.LTV_LTRID
  AND lt.LTR_LANID = ltv.LTV_LANID;

INSERT INTO STM_LITERAL_TRANSLATION_VALUE (LTV_ID, LTV_LTRID, LTV_LANID, LTV_VALUE)
SELECT base.NEXT_ID + ROW_NUMBER() OVER (ORDER BY lt.LTR_ID) - 1,
       lt.LTR_ID,
       lt.LTR_LANID,
       lt.LTR_LITERAL
FROM STM_LITERAL_TRANSLATION lt
CROSS JOIN (SELECT COALESCE(MAX(LTV_ID), 0) + 1 AS NEXT_ID FROM STM_LITERAL_TRANSLATION_VALUE) base
WHERE NOT EXISTS (
  SELECT 1
  FROM STM_LITERAL_TRANSLATION_VALUE existing
  WHERE existing.LTV_LTRID = lt.LTR_ID
    AND existing.LTV_LANID = lt.LTR_LANID
);

ALTER TABLE STM_LITERAL_TRANSLATION
  ALTER COLUMN LTR_LANID SET NOT NULL;

ALTER TABLE STM_LITERAL_TRANSLATION
  ADD CONSTRAINT STM_LTR_FK_LAN FOREIGN KEY (LTR_LANID) REFERENCES STM_LANGUAGE;

UPDATE STM_SEQUENCE
SET SEQ_COUNT = (SELECT COALESCE(MAX(LTV_ID), 0) + 1 FROM STM_LITERAL_TRANSLATION_VALUE)
WHERE SEQ_NAME = 'LTV_ID';
