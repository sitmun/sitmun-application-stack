PROMPT === Muestras de forma TAS_PARAMS ===
-- Por qué: verificar a ojo que las consultas tienen "scope" y las básicas no.
SELECT tas.TAS_ID,
       tas.TAS_TTASKID,
       CASE
         WHEN tas.TAS_PARAMS IS NULL THEN 'NULL'
         WHEN DBMS_LOB.INSTR(tas.TAS_PARAMS, '"scope"') > 0 THEN 'con-scope'
         ELSE 'sin-scope'
       END AS pista_forma,
       DBMS_LOB.SUBSTR(tas.TAS_PARAMS, 200, 1) AS prefijo_params
  FROM STM_TASK tas
 WHERE tas.TAS_PARAMS IS NOT NULL
   AND ROWNUM <= 20
 ORDER BY tas.TAS_ID;

