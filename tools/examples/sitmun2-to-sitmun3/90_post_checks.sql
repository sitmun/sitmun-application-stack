-- Comprobaciones post-migración: recuentos y FK huérfanas (Oracle).
-- Por qué: detectar filas no migradas, filtros EXISTS demasiado estrictos y referencias
-- rotas antes del COMMIT.
-- Esperad origen ≈ destino para las entidades migradas y 0 filas en las consultas de huérfanos.

COLUMN entity FORMAT A24
COLUMN src_cnt FORMAT 9999999
COLUMN tgt_cnt FORMAT 9999999

